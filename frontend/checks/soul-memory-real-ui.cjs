/** Explicit isolated-fixture browser acceptance. No mock routes and no model calls. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { chromium } = require('playwright');
const marker = process.env.TWINTEAMS_ISOLATED_FIXTURE;
if (!marker) throw new Error('TWINTEAMS_ISOLATED_FIXTURE must name an acceptance-owned random-schema fixture marker.');
const fixture = JSON.parse(fs.readFileSync(marker, 'utf8'));
const base = fixture.urls[0]; const url = new URL(base);
if (url.hostname !== '127.0.0.1' || !url.port || ['8000', '8001', '5199', '5173'].includes(url.port)) throw new Error('Refusing non-isolated or standard application port.');
let browser; let page;
async function run() {
  browser = await chromium.launch({ headless: true, channel: process.env.TWINTEAMS_BROWSER_CHANNEL || 'chrome' });
  const context = await browser.newContext({ viewport: { width: 1360, height: 900 }, reducedMotion: 'reduce' });
  await context.addInitScript(() => localStorage.setItem('twinteams.locale', 'en'));
  page = await context.newPage(); const errors = []; const badResponses = []; const chatWrites = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().includes('/api/me/twin') && response.status() >= 500) badResponses.push([response.status(), response.url()]); });
  page.on('request', request => { if (request.method() === 'POST' && /\/api\/chats\/[^/]+\/(messages|requests)/.test(request.url())) chatWrites.push(request.url()); });
  await page.goto(`${base}/#/my-twin/soul`);
  await page.getByPlaceholder('DEV-AAA').fill(fixture.username);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByLabel('Soul content', { exact: true }).waitFor();
  const api = context.request;
  async function json(path) { const response = await api.get(base + '/api' + path); assert.equal(response.status(), 200, await response.text()); return response.json(); }
  const original = await json('/me/twin/soul');
  await page.getByLabel('Soul content', { exact: true }).fill('Isolated Soul browser draft');
  await page.getByRole('tab', { name: 'Skills', exact: true }).click();
  await page.getByRole('tab', { name: 'Soul', exact: true }).click();
  assert.equal(await page.getByLabel('Soul content', { exact: true }).inputValue(), 'Isolated Soul browser draft');
  const remote = await api.put(base + '/api/me/twin/soul', { data: { content: 'Isolated remote Soul', expected_version: original.version } });
  assert.equal(remote.status(), 200); const changed = await remote.json();
  const stale = await api.put(base + '/api/me/twin/soul', { data: { content: 'Must never overwrite', expected_version: original.version } });
  assert.equal(stale.status(), 409); assert.equal((await stale.json()).current.content, 'Isolated remote Soul');
  await page.getByText('Isolated remote Soul', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Soul content', { exact: true }).inputValue(), 'Isolated Soul browser draft');
  assert.equal(await page.getByRole('button', { name: 'Save', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Keep draft and use current version', exact: true }).click();
  await page.getByLabel('Soul content', { exact: true }).fill('Isolated merged Soul');
  await page.getByRole('button', { name: 'Save', exact: true }).click(); await page.getByText('Saved', { exact: true }).waitFor();
  const savedSoul = await json('/me/twin/soul'); assert.equal(savedSoul.content, 'Isolated merged Soul'); assert.notEqual(savedSoul.version, changed.version); assert.match(savedSoul.version, /^[0-9a-f]{64}$/);
  const other = await browser.newContext();
  assert.equal((await other.request.post(base + '/api/auth/login', { data: { username: 'DEV-BBB' } })).status(), 200);
  assert.equal((await (await other.request.get(base + '/api/me/twin/soul')).json()).content, '');
  assert.equal((await other.request.put(base + '/api/me/twin/soul', { data: { content: 'forbidden target', expected_version: 0, owner_id: 'owner-alex' } })).status(), 422);
  assert.equal((await json('/me/twin/soul')).content, 'Isolated merged Soul');
  await page.getByRole('button', { name: 'Delete SOUL.md', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete SOUL.md', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' }); assert.equal((await json('/me/twin/soul')).content, '');
  await page.getByRole('tab', { name: 'Memory', exact: true }).click();
  await page.getByText('Enabled · Git', { exact: true }).waitFor();
  await page.getByText('Memory maintenance', { exact: true }).waitFor();
  const key = `ui-acceptance/${Date.now()}`;
  await page.getByRole('button', { name: 'Add memory', exact: true }).click();
  await page.getByLabel('Memory key', { exact: true }).fill(key);
  await page.getByLabel('Memory content', { exact: true }).fill('Isolated Git memory');
  await page.keyboard.press('Escape'); await page.getByRole('button', { name: 'Add memory', exact: true }).click();
  assert.equal(await page.getByLabel('Memory content', { exact: true }).inputValue(), 'Isolated Git memory');
  await page.getByRole('dialog').getByRole('button', { name: 'Save', exact: true }).click(); await page.getByRole('dialog').waitFor({ state: 'hidden' });
  const entryPath = '/me/twin/memory/entry?key=' + encodeURIComponent(key);
  const first = await json(entryPath); assert.match(first.version, /^[0-9a-f]{40}$/);
  assert.ok(first.sources.some(source => source.session_id.startsWith('twin-config:')));
  assert.equal((await other.request.get(base + '/api' + entryPath)).status(), 404);
  await other.request.post(base + '/api/auth/logout'); await other.close();
  const row = () => page.locator('.twin-memory-row').filter({ has: page.getByRole('heading', { name: key, exact: true }) });
  await row().click(); await page.getByRole('button', { name: 'Edit memory', exact: true }).click();
  await page.getByLabel('Memory content', { exact: true }).fill('Isolated local memory edit');
  const remoteMemory = await api.put(base + '/api' + entryPath, { data: { content: 'Isolated remote memory', expected_version: first.version } });
  assert.equal(remoteMemory.status(), 200); const second = await remoteMemory.json(); assert.notEqual(second.version, first.version);
  const staleMemory = await api.delete(base + '/api' + entryPath + '&expected_version=' + first.version);
  assert.equal(staleMemory.status(), 409); assert.equal((await staleMemory.json()).current.version, second.version);
  const save = page.getByRole('dialog').getByRole('button', { name: 'Save', exact: true });
  await page.getByRole('dialog').getByText('Isolated remote memory', { exact: true }).waitFor();
  assert.equal(await page.getByLabel('Memory content', { exact: true }).inputValue(), 'Isolated local memory edit');
  await page.getByRole('button', { name: 'Keep draft and use current version', exact: true }).click();
  await page.getByLabel('Memory content', { exact: true }).fill('Isolated merged Git memory');
  await save.click(); await page.getByRole('dialog').waitFor({ state: 'hidden' });
  const third = await json(entryPath); assert.notEqual(third.version, second.version); assert.equal(third.content, 'Isolated merged Git memory');
  await row().click(); await page.getByRole('button', { name: 'Delete memory', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete memory', exact: true }).click(); await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal((await api.get(base + '/api' + entryPath)).status(), 404);
  for (const name of ['Profile', 'Runtime', 'Skills', 'Credentials', 'Memory']) {
    await page.getByRole('tab', { name, exact: true }).click();
    await page.getByRole('tabpanel').waitFor();
    assert.equal(await page.getByRole('tab', { name, exact: true }).getAttribute('aria-selected'), 'true');
  }
  for (const path of ['/me/twin', '/me/twin/runtime', '/me/twin/skills', '/me/twin/credentials', '/me/twin/memory/status']) await json(path);
  await page.locator('.twin-memory-row').first().waitFor();
  await page.screenshot({ path: '/tmp/twinteams-soul-memory-real-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Add memory', exact: true }).click();
  await page.getByLabel('Memory key', { exact: true }).fill('ui-acceptance/mobile-unsaved');
  await page.getByLabel('Memory content', { exact: true }).fill('Unsaved isolated mobile draft');
  const box = await page.getByRole('dialog').boundingBox(); assert.ok(box.x >= 0 && box.x + box.width <= 390);
  await page.screenshot({ path: '/tmp/twinteams-soul-memory-real-mobile.png', fullPage: true });
  await page.keyboard.press('Escape');
  assert.deepEqual(errors, []); assert.deepEqual(badResponses, []); assert.deepEqual(chatWrites, []);
  await api.post(base + '/api/auth/logout'); await browser.close();
  const report = { isolated_base: base, mock_routes: false, cross_owner_isolation: true, old_tab_regression: true, soul_versions: [original.version, changed.version, savedSoul.version], memory_versions: [first.version, second.version, third.version], errors, badResponses, chatWrites, result: 'passed' };
  fs.writeFileSync('/tmp/twinteams-soul-memory-real-report.json', JSON.stringify(report, null, 2));
  console.log('PASS real isolated PostgreSQL + Git Soul/Memory CRUD, conflicts, drafts, Git versions, Dream status, mobile; no mock routes, chat writes or model calls.');
}
run().catch(async error => { console.error(error); if (page) { console.error((await page.locator('body').innerText()).slice(0, 3000)); await page.screenshot({ path: '/tmp/twinteams-soul-memory-real-error.png' }).catch(() => {}); } await browser?.close(); process.exitCode = 1; });
